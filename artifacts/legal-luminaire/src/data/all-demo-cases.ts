export const DEMO_CATEGORIES = [
  "All",
  "Criminal",
  "Civil",
  "Writ",
  "Consumer",
  "Commercial",
  "Infrastructure",
  "Financial Crime",
] as const;

export type DemoCategory = typeof DEMO_CATEGORIES[number];

export function filterDemoCases(
  cases: DemoCaseCard[],
  category: DemoCategory,
  search: string = ""
): DemoCaseCard[] {
  let filtered = cases;
  if (category !== "All") {
    filtered = filtered.filter(c => c.category === category);
  }
  if (search.trim()) {
    const q = search.toLowerCase();
    filtered = filtered.filter(c =>
      c.title.toLowerCase().includes(q) ||
      c.summary.toLowerCase().includes(q) ||
      c.charges.toLowerCase().includes(q) ||
      c.keyGround.toLowerCase().includes(q)
    );
  }
  return filtered;
}
