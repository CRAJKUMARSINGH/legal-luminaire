export function getTemplateById(id: string): DraftTemplate | undefined {
  return DRAFT_TEMPLATES.find((t) => t.id === id);
}

export function getTemplatesByFamily(family: string): DraftTemplate[] {
  return DRAFT_TEMPLATES.filter((t) => t.matterFamily === family);
}

export function getTemplatesByCategory(category: MatterCategory): DraftTemplate[] {
  return DRAFT_TEMPLATES.filter((t) => t.category === category);
}

export function getTemplatesByLanguage(lang: DraftLanguage): DraftTemplate[] {
  return DRAFT_TEMPLATES.filter((t) => t.language === lang);
}

export function searchTemplates(query: string): DraftTemplate[] {
  const q = query.toLowerCase();
  return DRAFT_TEMPLATES.filter(
    (t) =>
      t.title.toLowerCase().includes(q) ||
      (t.titleHi ?? "").includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.tags.some((tag) => tag.toLowerCase().includes(q)) ||
      t.court.toLowerCase().includes(q),
  );
}

