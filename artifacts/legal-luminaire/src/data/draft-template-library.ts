export function tierBadgeClass(tier: VerificationTier): string {
  switch (tier) {
    case "COURT_SAFE": return "bg-emerald-100 text-emerald-800 border-emerald-300";
    case "VERIFIED":   return "bg-blue-100 text-blue-800 border-blue-300";
    case "SECONDARY":  return "bg-amber-100 text-amber-800 border-amber-300";
    case "PENDING":    return "bg-red-100 text-red-800 border-red-300";
  }
}

